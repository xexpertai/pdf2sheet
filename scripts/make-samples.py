A4 = (595.0, 842.0)
DEMO_LABEL = "DEMO DATA - fictional sample generated by scripts/make-samples.py"


def text_width(s, size, bold=False):
    table = _HELV_BOLD if bold else _HELV
    return sum(table[ord(c) - 32] for c in s) * size / 1000.0


def _esc(s):
    return s.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")


class Page:
    """Collects drawing operations for one page (origin top-left, y grows down)."""

    def __init__(self, size=A4):
        self.w, self.h = size
        self.ops = []
        self.images = []  # (name, width, height, flate_bytes)

    def text(self, x, y, s, size=10, bold=False, align="left"):
        """Draw text with its baseline at y (measured from the top of the page)."""
        if align == "right":
            x -= text_width(s, size, bold)
        elif align == "center":
            x -= text_width(s, size, bold) / 2
        font = "F2" if bold else "F1"
        self.ops.append(
            f"BT /{font} {size:g} Tf {x:.2f} {self.h - y:.2f} Td ({_esc(s)}) Tj ET"
        )

    def line(self, x0, y0, x1, y1, width=0.5, gray=0.6):
        self.ops.append(
            f"{gray:g} G {width:g} w {x0:.2f} {self.h - y0:.2f} m {x1:.2f} {self.h - y1:.2f} l S"
        )

    def image(self, x, y, w, h, px_w, px_h, gray_bytes):
        name = f"Im{len(self.images) + 1}"
        self.images.append((name, px_w, px_h, zlib.compress(gray_bytes, 9)))
        self.ops.append(f"q {w:.2f} 0 0 {h:.2f} {x:.2f} {self.h - y - h:.2f} cm /{name} Do Q")

    def label(self):
        self.text(40, 28, DEMO_LABEL, size=7)


def write_pdf(path, pages, title):
    """Serialise pages into a minimal, valid PDF 1.4 file."""
    objs = []  # index i -> bytes of object (i+1)

    def add(body):
        objs.append(body)
        return len(objs)

    catalog = add(None)
    pages_id = add(None)
    f1 = add(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>")
    f2 = add(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>")
    page_ids = []
    for p in pages:
        xobjs = []
        for name, pw, ph, data in p.images:
            img = add(
                f"<< /Type /XObject /Subtype /Image /Width {pw} /Height {ph} /ColorSpace /DeviceGray "
                f"/BitsPerComponent 8 /Filter /FlateDecode /Length {len(data)} >>\nstream\n".encode()
                + data + b"\nendstream"
            )
            xobjs.append(f"/{name} {img} 0 R")
        content = "\n".join(p.ops).encode("latin-1")
        cid = add(f"<< /Length {len(content)} >>\nstream\n".encode() + content + b"\nendstream")
        res = f"/Font << /F1 {f1} 0 R /F2 {f2} 0 R >>"
        if xobjs:
            res += " /XObject << " + " ".join(xobjs) + " >>"
        pid = add(
            f"<< /Type /Page /Parent {pages_id} 0 R /MediaBox [0 0 {p.w:g} {p.h:g}] "
            f"/Resources << {res} >> /Contents {cid} 0 R >>".encode()
        )
        page_ids.append(pid)
    objs[catalog - 1] = f"<< /Type /Catalog /Pages {pages_id} 0 R >>".encode()
    kids = " ".join(f"{i} 0 R" for i in page_ids)
    objs[pages_id - 1] = f"<< /Type /Pages /Kids [{kids}] /Count {len(page_ids)} >>".encode()
    info = add(f"<< /Title ({_esc(title)}) /Producer (pdf2sheet make-samples.py) >>".encode())

    out = io.BytesIO()
    out.write(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets = []
    for i, body in enumerate(objs, start=1):
        offsets.append(out.tell())
        out.write(f"{i} 0 obj\n".encode() + body + b"\nendobj\n")
    xref = out.tell()
    out.write(f"xref\n0 {len(objs) + 1}\n0000000000 65535 f \n".encode())
    for off in offsets:
        out.write(f"{off:010d} 00000 n \n".encode())
    out.write(
        f"trailer\n<< /Size {len(objs) + 1} /Root {catalog} 0 R /Info {info} 0 R >>\n"
        f"startxref\n{xref}\n%%EOF\n".encode()
    )
    with open(path, "wb") as fh:
        fh.write(out.getvalue())


def money(v, symbol=""):
    s = f"{abs(v):,.2f}"
    return f"({symbol}{s})" if v < 0 else f"{symbol}{s}"


def wrap(s, width_pt, size):
    words, lines, cur = s.split(), [], ""
    for w in words:
        cand = f"{cur} {w}".strip()
        if cur and text_width(cand, size) > width_pt:
            lines.append(cur)
            cur = w
        else:
            cur = cand
    if cur:
        lines.append(cur)
    return lines


