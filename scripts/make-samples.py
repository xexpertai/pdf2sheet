def scanned(out_dir):
    """An image-only page (no text layer) that looks like a scanned table."""
    W, H = 600, 800
    px = bytearray([250]) * (W * H)

    def rect(x0, y0, x1, y1, v):
        for yy in range(y0, y1):
            px[yy * W + x0: yy * W + x1] = bytes([v]) * (x1 - x0)

    def stamp(x, y, s, scale):
        for ch in s:
            for r, bits in enumerate(_GLYPHS[ch]):
                for c, b in enumerate(bits):
                    if b == "1":
                        rect(x + c * scale, y + r * scale, x + (c + 1) * scale, y + (r + 1) * scale, 30)
            x += 6 * scale

    stamp(60, 40, "DEMO DATA SCAN", 6)
    for r in range(13):  # table grid with grey "text" bars
        y = 160 + r * 40
        rect(50, y, 550, y + 2, 120)
        if r < 12:
            for x0, x1 in ((60, 140), (160, 380), (400, 460), (480, 540)):
                rect(x0, y + 14, x1 if r == 0 else x0 + (x1 - x0) * (3 + (r * 7 + x0) % 5) // 7, y + 26, 90)
    for x in (50, 150, 390, 470, 550):
        rect(x, 160, x + 2, 642, 120)
    p = Page()
    p.image(0, 0, A4[0], A4[1], W, H, bytes(px))
    write_pdf(os.path.join(out_dir, "scanned-demo.pdf"), [p], "Scanned page (DEMO DATA)")


