ADJ = ["Steel", "Brass", "Nylon", "Zinc", "Copper", "Rubber", "Ceramic", "Oak", "Alloy", "Glass"]
NOUN = ["washer", "hinge", "bracket", "bolt", "spacer", "clamp", "valve", "bearing", "gasket", "pin"]
UNITS = ["pc", "box", "pack", "kg", "set"]


def price_list(out_dir):
    """3 pages x 40 rows, 5 columns; header repeated on each page."""
    rng = random.Random(1001)
    cols = [(40, "left", "SKU"), (105, "left", "Product"), (330, "left", "Unit"),
            (440, "right", "Stock"), (555, "right", "Price")]
    pages = []
    n = 0
    for pno in range(1, 4):
        p = Page()
        p.label()
        p.text(40, 60, "Northwind Fictional Supplies - Price list Q3", size=14, bold=True)
        y = 95
        for x, al, name in cols:
            p.text(x, y, name, bold=True, align=al)
        p.line(40, y + 5, 555, y + 5)
        y += 18
        for _ in range(40):
            n += 1
            sku = f"NW-{n:04d}"
            prod = f"{rng.choice(ADJ)} {rng.choice(NOUN)} {rng.randint(2, 40)} mm"
            unit = rng.choice(UNITS)
            stock = f"{rng.randint(0, 9000):,}"
            price = money(rng.randint(15, 250000) / 100)
            for (x, al, _), v in zip(cols, [sku, prod, unit, stock, price]):
                p.text(x, y, v, align=al)
            y += 15
        p.text(40, 800, f"Page {pno} of 3 - prices exclude tax", size=8)
        pages.append(p)
    write_pdf(os.path.join(out_dir, "price-list-demo.pdf"), pages, "Price list (DEMO DATA)")


def invoice(out_dir):
    rng = random.Random(2002)
    p = Page()
    p.label()
    p.text(40, 60, "INVOICE - Fictional Widgets Co. (DEMO DATA)", size=16, bold=True)
    p.text(40, 82, "Invoice no: DEMO-0042    Date: 12/03/2026")
    p.text(40, 96, "Bill to: Example Customer Pvt Ltd, 1 Sample Road, Testville")
    cols = [(40, "left", "Item"), (90, "left", "Description"), (380, "right", "Qty"),
            (470, "right", "Unit Price"), (555, "right", "Amount")]
    y = 140
    for x, al, name in cols:
        p.text(x, y, name, bold=True, align=al)
    p.line(40, y + 5, 555, y + 5)
    y += 18
    subtotal_cents = 0
    for i in range(1, 13):
        qty = rng.randint(1, 25)
        unit_cents = rng.randint(250, 189900)
        amt = qty * unit_cents
        subtotal_cents += amt
        desc = f"{rng.choice(ADJ)} {rng.choice(NOUN)} assembly kit"
        row = [str(i), desc, str(qty), money(unit_cents / 100, "$"), money(amt / 100, "$")]
        for (x, al, _), v in zip(cols, row):
            p.text(x, y, v, align=al)
        y += 16
    p.line(40, y - 8, 555, y - 8)
    y += 20
    tax = round(subtotal_cents * 0.18)
    p.text(470, y, "Subtotal", bold=True, align="right")
    p.text(555, y, money(subtotal_cents / 100, "$"), align="right")
    p.text(470, y + 16, "Tax 18%", align="right")
    p.text(555, y + 16, money(tax / 100, "$"), align="right")
    p.text(470, y + 32, "Total", bold=True, align="right")
    p.text(555, y + 32, money((subtotal_cents + tax) / 100, "$"), bold=True, align="right")
    p.text(40, 790, "Thank you for your fictional business. Payment due in 30 days.", size=8)
    write_pdf(os.path.join(out_dir, "invoice-demo.pdf"), [p], "Invoice (DEMO DATA)")


def statement(out_dir, expected_dir):
    """Bank-style statement with wrapped descriptions and debit/credit columns."""
    rng = random.Random(3003)
    descs = [
        "Card purchase - Fictional Grocery Mart, Sample City branch, ref 88213",
        "Salary credit",
        "Transfer to savings",
        "Utility bill payment - Example Power and Water Board, account 0042 quarterly charge",
        "ATM withdrawal",
        "Online order - Demo Books Store",
        "Refund - Placeholder Airlines booking change fee reversed after customer request",
        "Interest credit",
        "Standing order - Rent to Test Housing Society, flat 12B",
        "Mobile recharge",
        "Card purchase - Imaginary Cafe",
        "Insurance premium - Sample Mutual policy 77-1234 annual renewal instalment",
        "Cheque deposit 004512",
        "Bank charges",
    ]
    header = ["Date", "Description", "Debit", "Credit", "Balance"]
    cols = [(40, "left"), (110, "left"), (390, "right"), (465, "right"), (555, "right")]
    desc_width = 230
    p = Page()
    p.label()
    p.text(40, 60, "Statement of account - Demo Bank (DEMO DATA)", size=14, bold=True)
    p.text(40, 80, "Account: 0000-DEMO-1234    Period: 01/09/2026 to 30/09/2026")
    y = 120
    for (x, al), name in zip(cols, header):
        p.text(x, y, name, bold=True, align=al)
    p.line(40, y + 5, 555, y + 5)
    y += 18
    balance = 125000  # cents
    rows = [header]
    for i, d in enumerate(descs):
        day = 1 + i * 2
        date = f"{day:02d}/09/2026"
        is_credit = any(k in d for k in ("Salary", "Refund", "Interest", "deposit"))
        amt = rng.randint(500, 250000) if is_credit else rng.randint(300, 60000)
        balance += amt if is_credit else -amt
        debit = "" if is_credit else money(amt / 100)
        credit = money(amt / 100) if is_credit else ""
        bal = money(balance / 100)
        lines = wrap(d, desc_width, 10)
        vals = [date, lines[0], debit, credit, bal]
        for (x, al), v in zip(cols, vals):
            if v:
                p.text(x, y, v, align=al)
        for extra in lines[1:]:
            y += 12
            p.text(cols[1][0], y, extra)
        y += 16
        rows.append([date, " ".join(lines), debit, credit, bal])
    p.line(40, y - 8, 555, y - 8)
    p.text(40, y + 20, f"Closing balance {money(balance / 100)} - this is not a real bank statement.", size=9)
    write_pdf(os.path.join(out_dir, "statement-demo.pdf"), [p], "Statement (DEMO DATA)")
    with open(os.path.join(expected_dir, "statement-demo.csv"), "w", newline="", encoding="utf-8") as fh:
        csv.writer(fh, lineterminator="\r\n").writerows(rows)


