"""Generate the fictional DEMO DATA sample PDFs used by pdf2sheet's tests and demo.

Pure standard library (no reportlab): it writes small, uncompressed-text PDFs with
the built-in Helvetica font, so the output is byte-for-byte reproducible.

    python3 scripts/make-samples.py            # writes into ./samples
    python3 scripts/make-samples.py OUT_DIR

Every page carries a "DEMO DATA" label. All names, amounts and references are
invented by a seeded pseudo-random generator; none refer to real people or firms.
"""

